# 설치 파일에 넣을 파일 목록(.nsh)을 만든다. WorshipPresenter.nsi 가 컴파일할 때 부른다.
#   powershell -File filelist.ps1 -Src <스테이징 폴더> -Out <만들 .nsh>
# 이 목록 하나로 (1) 풀어 넣기 (2) 설치 폴더의 파일 목록(wp-files.txt) 적기 (3) 제거를 모두 한다.
# → 설치·제거가 '우리가 넣은 파일'만 건드리고, *.dll 이나 web\ 통째 같은 묶음 삭제를 하지 않는다.
param(
  [Parameter(Mandatory = $true)][string]$Src,
  [Parameter(Mandatory = $true)][string]$Out
)
$ErrorActionPreference = 'Stop'
$Src = (Resolve-Path -LiteralPath $Src).Path.TrimEnd('\')

$files = New-Object System.Collections.Generic.List[string]
foreach ($name in 'WorshipPresenter.exe', 'wp-output.exe', 'WorshipPresenter.ico', 'bible.db', 'LICENSE.txt', 'THIRD_PARTY_NOTICES.md', 'OFL-Pretendard.txt') {
  if (-not (Test-Path -LiteralPath (Join-Path $Src $name) -PathType Leaf)) { throw "스테이징 폴더에 $name 이 없습니다: $Src" }
  $files.Add($name)
}
$web = Join-Path $Src 'web'
if (-not (Test-Path -LiteralPath $web -PathType Container)) { throw "스테이징 폴더에 web\ 이 없습니다: $Src" }
Get-ChildItem -LiteralPath $web -Recurse -File | Sort-Object FullName | ForEach-Object { $files.Add($_.FullName.Substring($Src.Length + 1)) }
# 실행 파일 옆 DLL (지금은 없지만 빌드에 따라 생길 수 있다). web\ 안의 것은 위에서 이미 넣었다
Get-ChildItem -LiteralPath $Src -Recurse -File -Filter *.dll | Sort-Object FullName | ForEach-Object {
  $rel = $_.FullName.Substring($Src.Length + 1)
  if (-not $files.Contains($rel)) { $files.Add($rel) }
}

$dirs = New-Object System.Collections.Generic.List[string]
foreach ($rel in $files) {
  # 설치 쪽은 목록의 길을 글자 그대로 쓴다: 영문·숫자와 흔한 기호만 받는다 ($ " * ? : .. 등은 NSIS·삭제에서 뜻이 달라진다)
  if ($rel -notmatch '^[A-Za-z0-9 _\-\.\\\(\)\+@,~\[\]]+$' -or $rel -match '\.\.' -or $rel.Length -gt 240) {
    throw "설치 목록에 넣을 수 없는 파일 이름입니다: $rel"
  }
  $d = Split-Path $rel -Parent
  while ($d) {
    if (-not $dirs.Contains($d)) { $dirs.Add($d) }
    $d = Split-Path $d -Parent
  }
}
# 깊은 폴더부터 (비었을 때만 지우는 RMDir 를 안쪽부터 하려고)
$dirs = @($dirs | Sort-Object { ($_ -split '\\').Count }, { $_ } -Descending)

$o = New-Object System.Collections.Generic.List[string]
$o.Add('; generated by installer\filelist.ps1 - do not edit') # 이 파일은 ASCII 로만 쓴다
$o.Add('!macro WP_EACH_FILE CB')
foreach ($rel in $files) {
  $d = Split-Path $rel -Parent
  $sub = if ($d) { "\$d" } else { '' }
  $o.Add("  !insertmacro `${CB} `"$sub`" `"$rel`"")
}
$o.Add('!macroend')
$o.Add('!macro WP_EACH_DIR CB')
foreach ($d in $dirs) { $o.Add("  !insertmacro `${CB} `"$d`"") }
$o.Add('!macroend')
[IO.File]::WriteAllLines($Out, $o, (New-Object Text.ASCIIEncoding))
